# SOLICITA AO USUÁRIO DOIS NÚMEROS
# int () = converte para número inteiro 
# float () = converte para número com casa decimal
primeiro_numero = int( input("Digite um número:") )
segundo_numero  = float ( input("Digite outro número:") )

# CRIA VARIÁVEIS PARA OS RESULTADOS
# Soma
soma = primeiro_numero + segundo_numero
#Subtração 
sub = primeiro_numero - segundo_numero
#Multiplicação
mult = primeiro_numero * segundo_numero
#Divisão
div = primeiro_numero / segundo_numero

#MOSTRAR RESULTADOS
print("A soma é:", soma)
print("A subtração é:", sub)
print("A multiplicação é:", mult)
print("A divisão é:", div)